-- Ticket #112 (app, 26/11/2026): pantalla "Tareas de hoy" (Hoy / Aplazadas / Completadas). Las tareas son las Alertas de
-- tareas (se calculan de cada módulo, ver alertas.service.ts); aquí se guarda lo que cada usuario hace con ellas:
-- aplazarla hasta una fecha o marcarla completada. Es personal (cada usuario ve solo lo suyo).
-- fecha_alerta: el vencimiento de la alerta cuando se marcó; si la alerta cambia de fecha (otra cuota, otra póliza),
-- vuelve a aparecer como pendiente.
-- Tabla nueva, no modifica datos existentes. Idempotente.

CREATE TABLE IF NOT EXISTS public.tarea_estado (
    id_tarea_estado  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auth_user_id     uuid NOT NULL DEFAULT auth.uid(),
    id_alerta        text NOT NULL CHECK (length(id_alerta) BETWEEN 1 AND 120),
    estado           text NOT NULL CHECK (estado IN ('aplazada', 'completada')),
    aplazada_hasta   date,
    fecha_alerta     date,
    updated_at       timestamptz NOT NULL DEFAULT now(),
    UNIQUE (auth_user_id, id_alerta),
    CHECK (estado <> 'aplazada' OR aplazada_hasta IS NOT NULL)
);

ALTER TABLE public.tarea_estado ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tarea_estado_propias ON public.tarea_estado;
CREATE POLICY tarea_estado_propias ON public.tarea_estado
    TO authenticated USING (auth_user_id = auth.uid()) WITH CHECK (auth_user_id = auth.uid());
GRANT SELECT, INSERT, UPDATE, DELETE ON public.tarea_estado TO authenticated;

