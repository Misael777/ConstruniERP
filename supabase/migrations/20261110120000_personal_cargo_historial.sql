-- Historial de cargos del trabajador (a pedido del usuario, 10/11/2026): en Datos laborales un trabajador puede
-- tener varios cargos a lo largo del tiempo, cada uno con las fechas en que lo ejerció. El tramo sin fecha_fin
-- es el cargo actual; la app copia ese cargo a personal.cargo para que listas y filtros sigan igual.
-- Se edita desde la ficha (PersonalModal) y se borra en cascada con la ficha.
-- Idempotente.

CREATE TABLE IF NOT EXISTS public.personal_cargo_historial (
    id_cargo_historial bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_personal bigint NOT NULL REFERENCES public.personal (id_personal) ON DELETE CASCADE,
    cargo varchar(100) NOT NULL CHECK (btrim(cargo) <> ''),
    fecha_inicio date NOT NULL,
    fecha_fin date,
    observacion varchar(200),
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT personal_cargo_historial_fechas_check CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);
COMMENT ON TABLE public.personal_cargo_historial IS 'Cargos que ejerció cada trabajador, con desde/hasta (hasta vacío = cargo actual).';

CREATE INDEX IF NOT EXISTS idx_personal_cargo_historial_personal
    ON public.personal_cargo_historial (id_personal, fecha_inicio DESC);

ALTER TABLE public.personal_cargo_historial ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS personal_cargo_historial_autenticados ON public.personal_cargo_historial;
CREATE POLICY personal_cargo_historial_autenticados ON public.personal_cargo_historial
    TO authenticated USING (true) WITH CHECK (true);
GRANT SELECT, INSERT, UPDATE, DELETE ON public.personal_cargo_historial TO authenticated;

-- Punto de partida: el cargo que ya tenga cada ficha pasa a ser su cargo actual (desde su ingreso o su alta).
INSERT INTO public.personal_cargo_historial (id_personal, cargo, fecha_inicio)
SELECT p.id_personal, btrim(p.cargo), COALESCE(p.fecha_ingreso, p.created_at::date, current_date)
FROM public.personal p
WHERE p.cargo IS NOT NULL AND btrim(p.cargo) <> ''
  AND NOT EXISTS (SELECT 1 FROM public.personal_cargo_historial h WHERE h.id_personal = p.id_personal);

