-- Historial de asignaciones del trabajador (a pedido del usuario, 12/11/2026): obras o áreas, huelleros y
-- referentes que tuvo cada trabajador, con desde/hasta. Se llena solo con triggers, venga el cambio de la ficha,
-- de Asistencia → Configuración, de fn_personal_mover o del receptor del huellero; la app solo lo lee.
--   tipo 'obra'      → personal.id_centro_costo
--   tipo 'huellero'  → filas de personal_huellero (alta = asignado, baja = retirado)
--   tipo 'referente' → personal.referente_nombre / referente_cargo
-- El tramo con fecha_fin NULL es el vigente. `detalle` guarda el texto del momento (código y nombre de la obra,
-- nombre y serie del huellero) por si luego se borra o renombra.
-- Idempotente.

CREATE TABLE IF NOT EXISTS public.personal_historial_asignacion (
    id_historial bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_personal bigint NOT NULL REFERENCES public.personal (id_personal) ON DELETE CASCADE,
    tipo varchar(10) NOT NULL CHECK (tipo IN ('obra', 'huellero', 'referente')),
    id_centro_costo bigint REFERENCES public.centro_costo (id_centro_costo) ON DELETE SET NULL,
    id_dispositivo bigint REFERENCES public.asistencia_dispositivo (id_dispositivo) ON DELETE SET NULL,
    referente_nombre varchar(150),
    referente_cargo varchar(50),
    detalle varchar(250),
    fecha_inicio timestamptz NOT NULL DEFAULT now(),
    fecha_fin timestamptz,
    registrado_por uuid DEFAULT auth.uid(),
    created_at timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE public.personal_historial_asignacion IS 'Obras, huelleros y referentes que tuvo cada trabajador (desde/hasta). Lo llenan triggers.';

CREATE INDEX IF NOT EXISTS idx_personal_historial_asignacion_personal
    ON public.personal_historial_asignacion (id_personal, tipo, fecha_inicio DESC);

ALTER TABLE public.personal_historial_asignacion ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS personal_historial_asignacion_lectura ON public.personal_historial_asignacion;
CREATE POLICY personal_historial_asignacion_lectura ON public.personal_historial_asignacion
    FOR SELECT TO authenticated USING (true);
GRANT SELECT ON public.personal_historial_asignacion TO authenticated;

-- Texto de una obra o área: "PROY-13 · Nombre del proyecto".
CREATE OR REPLACE FUNCTION public.fn_historial_detalle_obra(p_id bigint) RETURNS varchar
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
    SELECT left(concat_ws(' · ', c.codigo, COALESCE(NULLIF(btrim(p.nombre_proyecto), ''), c.nombre)), 250)
    FROM centro_costo c LEFT JOIN proyecto p ON p.id_proyecto = c.id_proyecto
    WHERE c.id_centro_costo = p_id;
$$;

-- Texto de un huellero: "Nombre · SN".
CREATE OR REPLACE FUNCTION public.fn_historial_detalle_huellero(p_id bigint) RETURNS varchar
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
    SELECT left(concat_ws(' · ', COALESCE(NULLIF(btrim(d.nombre), ''), 'Huellero'), d.numero_serie), 250)
    FROM asistencia_dispositivo d WHERE d.id_dispositivo = p_id;
$$;

-- Obra y referente: al dar de alta y al cambiar.
CREATE OR REPLACE FUNCTION public.fn_personal_historial_asignacion() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
    IF TG_OP = 'UPDATE' AND NEW.id_centro_costo IS DISTINCT FROM OLD.id_centro_costo OR TG_OP = 'INSERT' THEN
        UPDATE personal_historial_asignacion SET fecha_fin = now()
        WHERE id_personal = NEW.id_personal AND tipo = 'obra' AND fecha_fin IS NULL;
        IF NEW.id_centro_costo IS NOT NULL THEN
            INSERT INTO personal_historial_asignacion (id_personal, tipo, id_centro_costo, detalle)
            VALUES (NEW.id_personal, 'obra', NEW.id_centro_costo, fn_historial_detalle_obra(NEW.id_centro_costo));
        END IF;
    END IF;

    IF TG_OP = 'INSERT'
       OR NULLIF(btrim(NEW.referente_nombre), '') IS DISTINCT FROM NULLIF(btrim(OLD.referente_nombre), '')
       OR NEW.referente_cargo IS DISTINCT FROM OLD.referente_cargo THEN
        UPDATE personal_historial_asignacion SET fecha_fin = now()
        WHERE id_personal = NEW.id_personal AND tipo = 'referente' AND fecha_fin IS NULL;
        IF NULLIF(btrim(NEW.referente_nombre), '') IS NOT NULL THEN
            INSERT INTO personal_historial_asignacion (id_personal, tipo, referente_nombre, referente_cargo)
            VALUES (NEW.id_personal, 'referente', btrim(NEW.referente_nombre), NEW.referente_cargo);
        END IF;
    END IF;
    RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS trg_personal_historial_asignacion ON public.personal;
CREATE TRIGGER trg_personal_historial_asignacion
    AFTER INSERT OR UPDATE OF id_centro_costo, referente_nombre, referente_cargo ON public.personal
    FOR EACH ROW EXECUTE FUNCTION public.fn_personal_historial_asignacion();

-- Huelleros: asignado al insertar en personal_huellero, retirado al borrar. Si el borrado viene en cascada de
-- borrar la ficha, el historial se borra con ella (no se toca).
CREATE OR REPLACE FUNCTION public.fn_personal_huellero_historial() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO personal_historial_asignacion (id_personal, tipo, id_dispositivo, detalle)
        VALUES (NEW.id_personal, 'huellero', NEW.id_dispositivo, fn_historial_detalle_huellero(NEW.id_dispositivo));
    ELSIF EXISTS (SELECT 1 FROM personal WHERE id_personal = OLD.id_personal) THEN
        UPDATE personal_historial_asignacion SET fecha_fin = now()
        WHERE id_personal = OLD.id_personal AND tipo = 'huellero' AND id_dispositivo = OLD.id_dispositivo AND fecha_fin IS NULL;
    END IF;
    RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS trg_personal_huellero_historial ON public.personal_huellero;
CREATE TRIGGER trg_personal_huellero_historial
    AFTER INSERT OR DELETE ON public.personal_huellero
    FOR EACH ROW EXECUTE FUNCTION public.fn_personal_huellero_historial();

-- Punto de partida: lo que cada trabajador tiene hoy queda como su tramo vigente.
INSERT INTO public.personal_historial_asignacion (id_personal, tipo, id_centro_costo, detalle, fecha_inicio, registrado_por)
SELECT p.id_personal, 'obra', p.id_centro_costo, public.fn_historial_detalle_obra(p.id_centro_costo),
       COALESCE(p.fecha_ingreso::timestamp AT TIME ZONE 'America/Lima', p.created_at, now()), NULL
FROM public.personal p
WHERE p.id_centro_costo IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM public.personal_historial_asignacion h WHERE h.id_personal = p.id_personal AND h.tipo = 'obra');

INSERT INTO public.personal_historial_asignacion (id_personal, tipo, referente_nombre, referente_cargo, fecha_inicio, registrado_por)
SELECT p.id_personal, 'referente', btrim(p.referente_nombre), p.referente_cargo, COALESCE(p.fecha_ingreso::timestamp AT TIME ZONE 'America/Lima', p.created_at, now()), NULL
FROM public.personal p
WHERE NULLIF(btrim(p.referente_nombre), '') IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM public.personal_historial_asignacion h WHERE h.id_personal = p.id_personal AND h.tipo = 'referente');

INSERT INTO public.personal_historial_asignacion (id_personal, tipo, id_dispositivo, detalle, fecha_inicio, registrado_por)
SELECT ph.id_personal, 'huellero', ph.id_dispositivo, public.fn_historial_detalle_huellero(ph.id_dispositivo), COALESCE(ph.created_at, now()), NULL
FROM public.personal_huellero ph
WHERE NOT EXISTS (SELECT 1 FROM public.personal_historial_asignacion h
                  WHERE h.id_personal = ph.id_personal AND h.tipo = 'huellero' AND h.id_dispositivo = ph.id_dispositivo);

