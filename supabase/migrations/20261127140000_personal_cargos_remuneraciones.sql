-- Ticket #144 (26/11/2026, maqueta de la clienta): Cargo y remuneración de la ficha del trabajador.
--  - personal_cargo_historial.clasificacion: un trabajador tiene UN cargo principal vigente y puede tener cargos
--    secundarios a la vez ("Operario carpintero" principal + "Oficial albañil" secundario).
--  - personal_cargo_historial.aptitudes: aptitudes técnicas del cargo con su nivel, [{actividad, nivel}]
--    (nivel: basico | intermedio | avanzado). Alimentan personal.aptitudes, que usa el tareo (#118).
--  - personal_remuneracion_historial: historial de remuneraciones (desde, hasta, periodicidad, monto). La vigente se
--    copia a personal.periodicidad_pago / monto_pago / monto_pago_desde, que siguen usando el tareo y la planilla.
-- Punto de partida: la remuneración que ya tiene cada ficha pasa a ser su remuneración vigente. No modifica datos
-- existentes. Idempotente.

ALTER TABLE public.personal_cargo_historial ADD COLUMN IF NOT EXISTS clasificacion text NOT NULL DEFAULT 'principal';
DO $$ BEGIN
    ALTER TABLE public.personal_cargo_historial ADD CONSTRAINT personal_cargo_historial_clasificacion_check CHECK (clasificacion IN ('principal', 'secundario'));
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
ALTER TABLE public.personal_cargo_historial ADD COLUMN IF NOT EXISTS aptitudes jsonb NOT NULL DEFAULT '[]'::jsonb;

CREATE TABLE IF NOT EXISTS public.personal_remuneracion_historial (
    id_remuneracion  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_personal      bigint NOT NULL REFERENCES public.personal (id_personal) ON DELETE CASCADE,
    fecha_inicio     date NOT NULL,
    fecha_fin        date,
    periodicidad     text NOT NULL CHECK (periodicidad IN ('diaria', 'semanal', 'quincenal', 'mensual')),
    monto            numeric(12, 2) NOT NULL CHECK (monto >= 0),
    observacion      varchar(200),
    usuario          text,
    created_at       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT personal_remuneracion_fechas_check CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);
CREATE INDEX IF NOT EXISTS idx_personal_remuneracion_personal ON public.personal_remuneracion_historial (id_personal, fecha_inicio DESC);

ALTER TABLE public.personal_remuneracion_historial ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS personal_remuneracion_historial_rrhh ON public.personal_remuneracion_historial;
CREATE POLICY personal_remuneracion_historial_rrhh ON public.personal_remuneracion_historial
    TO authenticated USING (tiene_permiso('ver_rrhh_personal')) WITH CHECK (tiene_permiso('ver_rrhh_personal'));
GRANT SELECT, INSERT, UPDATE, DELETE ON public.personal_remuneracion_historial TO authenticated;

INSERT INTO public.personal_remuneracion_historial (id_personal, fecha_inicio, periodicidad, monto)
SELECT p.id_personal, COALESCE(p.monto_pago_desde, p.fecha_ingreso, p.created_at::date, current_date), p.periodicidad_pago, p.monto_pago
FROM public.personal p
WHERE p.monto_pago IS NOT NULL AND p.periodicidad_pago IN ('diaria', 'semanal', 'quincenal', 'mensual')
  AND NOT EXISTS (SELECT 1 FROM public.personal_remuneracion_historial h WHERE h.id_personal = p.id_personal);

