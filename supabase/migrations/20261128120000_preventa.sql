-- Ticket #46 "Submódulo de Pre-Venta" (Comercial): embudo de oportunidades comerciales antes de la venta, con vistas
-- Lista, Kanban y Calendario, y actividades agendadas (llamada, videollamada con enlace de Meet, visita en campo u
-- oficina, envío de proforma, contrato o brochure), según las imágenes de la clienta.
--   oportunidad           : una oportunidad del embudo (cliente o prospecto, etapa, valor, probabilidad, cierre...).
--   oportunidad_actividad : actividades agendadas de cada oportunidad (alimentan "Actividades próximas" y el calendario).
-- Permiso nuevo ver_comercial_preventa: se da a los roles que ya ven Ventas. Tablas nuevas; no modifica datos. Idempotente.

INSERT INTO public.permisos (nombre, descripcion)
SELECT 'ver_comercial_preventa', 'Pre-Venta: oportunidades comerciales y actividades del embudo'
WHERE NOT EXISTS (SELECT 1 FROM public.permisos WHERE nombre = 'ver_comercial_preventa');

INSERT INTO public.roles_permisos (rol_id, permiso_id)
SELECT DISTINCT rp.rol_id, nuevo.id
FROM public.roles_permisos rp
JOIN public.permisos viejo ON viejo.id = rp.permiso_id AND viejo.nombre = 'ver_comercial_ventas'
JOIN public.permisos nuevo ON nuevo.nombre = 'ver_comercial_preventa'
WHERE NOT EXISTS (SELECT 1 FROM public.roles_permisos x WHERE x.rol_id = rp.rol_id AND x.permiso_id = nuevo.id);

CREATE TABLE IF NOT EXISTS public.oportunidad (
    id_oportunidad      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo              text UNIQUE,
    id_cliente          bigint REFERENCES public.cliente (id_cliente) ON DELETE SET NULL,
    prospecto           text,
    nombre              text NOT NULL CHECK (btrim(nombre) <> '' AND length(nombre) <= 150),
    tipo                text,
    origen              text,
    id_ejecutivo        integer REFERENCES public.empleados (id) ON DELETE SET NULL,
    etapa               text NOT NULL DEFAULT 'prospecto'
                        CHECK (etapa IN ('prospecto', 'calificacion', 'visita_tecnica', 'propuesta', 'cotizacion', 'negociacion', 'adjudicada', 'perdida')),
    prioridad           text NOT NULL DEFAULT 'media' CHECK (prioridad IN ('alta', 'media', 'baja')),
    moneda              text NOT NULL DEFAULT 'PEN' CHECK (moneda IN ('PEN', 'USD')),
    valor_sin_igv       numeric(14,2) NOT NULL DEFAULT 0 CHECK (valor_sin_igv >= 0),
    con_igv             boolean NOT NULL DEFAULT true,
    probabilidad        integer NOT NULL DEFAULT 10 CHECK (probabilidad BETWEEN 0 AND 100),
    fecha_registro      date NOT NULL DEFAULT (now() AT TIME ZONE 'America/Lima')::date,
    fecha_cierre        date,
    vigencia_propuesta  date,
    tipo_comprobante    text,
    comision_porcentaje numeric(5,2),
    descripcion         text,
    notas               text,
    motivo_perdida      text,
    activo              boolean NOT NULL DEFAULT true,
    usuario_registro    text,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    CHECK (id_cliente IS NOT NULL OR NULLIF(btrim(prospecto), '') IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS idx_oportunidad_etapa ON public.oportunidad (etapa) WHERE activo;

-- Código PV-AAAA-00001 (correlativo por año) al crear.
CREATE OR REPLACE FUNCTION public.fn_oportunidad_codigo() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE v_anio text := to_char(COALESCE(NEW.fecha_registro, (now() AT TIME ZONE 'America/Lima')::date), 'YYYY');
BEGIN
    IF NEW.codigo IS NULL THEN
        PERFORM pg_advisory_xact_lock(hashtext('oportunidad_codigo_' || v_anio));
        SELECT format('PV-%s-%s', v_anio, lpad((COALESCE(max(split_part(codigo, '-', 3)::int), 0) + 1)::text, 5, '0'))
        INTO NEW.codigo FROM oportunidad WHERE codigo LIKE 'PV-' || v_anio || '-%';
    END IF;
    NEW.updated_at := now();
    RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_oportunidad_codigo ON public.oportunidad;
CREATE TRIGGER trg_oportunidad_codigo BEFORE INSERT OR UPDATE ON public.oportunidad
    FOR EACH ROW EXECUTE FUNCTION public.fn_oportunidad_codigo();

CREATE TABLE IF NOT EXISTS public.oportunidad_actividad (
    id_actividad     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_oportunidad   bigint REFERENCES public.oportunidad (id_oportunidad) ON DELETE CASCADE,
    tipo             text NOT NULL CHECK (tipo IN ('llamada', 'videollamada', 'visita_campo', 'visita_oficina', 'envio_proforma', 'envio_contrato', 'envio_brochure', 'reunion', 'seguimiento')),
    titulo           text NOT NULL CHECK (btrim(titulo) <> ''),
    fecha_hora       timestamptz NOT NULL,
    enlace           text,
    lugar            text,
    notas            text,
    responsable      text,
    completada       boolean NOT NULL DEFAULT false,
    usuario_registro text,
    created_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_oportunidad_actividad_fecha ON public.oportunidad_actividad (fecha_hora);

