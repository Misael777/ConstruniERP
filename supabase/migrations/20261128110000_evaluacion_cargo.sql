-- Ticket #152 (27/11/2026) "Evaluar cargo": evaluación del cargo de un trabajador desde su historial de cargos, con tres
-- formatos según el personal (imágenes de la clienta):
--   obrero      : aptitudes con rendimiento (unidad, esperado, real, cumplimiento) + calidad de ejecución y seguridad.
--   consultoria : aptitudes técnicas con calificación % + desempeño profesional por criterios con peso.
--   gerencial   : aptitudes gerenciales con peso + cumplimiento de objetivos (KPI) + ponderación aptitudes/objetivos.
-- Las tablas (aptitudes, criterios, KPI) van en jsonb: cada formato tiene sus columnas y la app las calcula.
-- Evalúa SOLO el jefe inmediato del trabajador (personal.id_jefe_inmediato) o un administrador; lo mismo para leer, más
-- quien tenga ver_rrhh_personal. "Dar de baja cargo" cierra el tramo evaluado (fecha_fin = fecha de evaluación).
-- Tabla nueva; no modifica datos existentes salvo el cierre del tramo al dar de baja. Idempotente.

CREATE TABLE IF NOT EXISTS public.personal_evaluacion_cargo (
    id_evaluacion          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_personal            bigint NOT NULL REFERENCES public.personal (id_personal) ON DELETE CASCADE,
    id_cargo_historial     bigint REFERENCES public.personal_cargo_historial (id_cargo_historial) ON DELETE SET NULL,
    formato                text NOT NULL CHECK (formato IN ('obrero', 'consultoria', 'gerencial')),
    cargo                  text NOT NULL CHECK (btrim(cargo) <> ''),
    periodo_inicio         date NOT NULL,
    periodo_fin            date NOT NULL CHECK (periodo_fin >= periodo_inicio),
    aptitudes              jsonb NOT NULL DEFAULT '[]'::jsonb,
    criterios              jsonb NOT NULL DEFAULT '[]'::jsonb,
    objetivos              jsonb NOT NULL DEFAULT '[]'::jsonb,
    peso_aptitudes         numeric(5,2),
    calificacion_final     numeric(5,2),
    observaciones          text,
    calidad_ejecucion      text,
    cumplimiento_seguridad text,
    evaluado_por           text NOT NULL CHECK (btrim(evaluado_por) <> ''),
    fecha_evaluacion       date NOT NULL,
    estado                 text NOT NULL CHECK (estado IN ('en_evaluacion', 'aprobado', 'ascenso', 'baja')),
    sustento               text NOT NULL CHECK (btrim(sustento) <> ''),
    cargo_ascenso          text,
    registrado_por         text,
    registrado_por_id      uuid DEFAULT auth.uid(),
    created_at             timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_evaluacion_cargo_personal ON public.personal_evaluacion_cargo (id_personal, fecha_evaluacion DESC);

-- ¿El usuario actual es el jefe inmediato de este trabajador?
CREATE OR REPLACE FUNCTION public.fn_es_jefe_de(p_id_personal bigint)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public' AS $$
    SELECT EXISTS (
        SELECT 1 FROM personal p JOIN empleados e ON e.id = p.id_jefe_inmediato
        WHERE p.id_personal = p_id_personal AND e.auth_user_id = auth.uid() AND e.estado = 'activo'
    );
$$;
REVOKE ALL ON FUNCTION public.fn_es_jefe_de(bigint) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.fn_es_jefe_de(bigint) TO authenticated;

ALTER TABLE public.personal_evaluacion_cargo ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS evaluacion_cargo_leer ON public.personal_evaluacion_cargo;
CREATE POLICY evaluacion_cargo_leer ON public.personal_evaluacion_cargo FOR SELECT TO authenticated
    USING (is_admin() OR tiene_permiso('ver_rrhh_personal') OR fn_es_jefe_de(id_personal));
GRANT SELECT ON public.personal_evaluacion_cargo TO authenticated;

-- Guardar (solo por aquí): valida quién evalúa y, si es "Dar de baja cargo", cierra el tramo evaluado.
CREATE OR REPLACE FUNCTION public.fn_guardar_evaluacion_cargo(p jsonb)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE
    v_personal bigint := (p->>'id_personal')::bigint;
    v_tramo    bigint := NULLIF(p->>'id_cargo_historial', '')::bigint;
    v_fecha    date   := (p->>'fecha_evaluacion')::date;
    v_estado   text   := p->>'estado';
    v_id       bigint;
BEGIN
    IF v_personal IS NULL THEN RAISE EXCEPTION 'Falta el trabajador.'; END IF;
    IF NOT (is_admin() OR fn_es_jefe_de(v_personal)) THEN
        RAISE EXCEPTION 'Solo el jefe inmediato del trabajador (o un administrador) puede evaluar su cargo.' USING ERRCODE = '42501';
    END IF;
    IF v_tramo IS NOT NULL AND NOT EXISTS (SELECT 1 FROM personal_cargo_historial WHERE id_cargo_historial = v_tramo AND id_personal = v_personal) THEN
        RAISE EXCEPTION 'El cargo evaluado no es de este trabajador.';
    END IF;
    IF v_estado = 'ascenso' AND NULLIF(btrim(p->>'cargo_ascenso'), '') IS NULL THEN
        RAISE EXCEPTION 'Indica el cargo de ascenso propuesto.';
    END IF;

    INSERT INTO personal_evaluacion_cargo (
        id_personal, id_cargo_historial, formato, cargo, periodo_inicio, periodo_fin, aptitudes, criterios, objetivos,
        peso_aptitudes, calificacion_final, observaciones, calidad_ejecucion, cumplimiento_seguridad, evaluado_por,
        fecha_evaluacion, estado, sustento, cargo_ascenso, registrado_por)
    VALUES (
        v_personal, v_tramo, p->>'formato', btrim(p->>'cargo'), (p->>'periodo_inicio')::date, (p->>'periodo_fin')::date,
        COALESCE(p->'aptitudes', '[]'::jsonb), COALESCE(p->'criterios', '[]'::jsonb), COALESCE(p->'objetivos', '[]'::jsonb),
        NULLIF(p->>'peso_aptitudes', '')::numeric, NULLIF(p->>'calificacion_final', '')::numeric, NULLIF(btrim(p->>'observaciones'), ''),
        NULLIF(p->>'calidad_ejecucion', ''), NULLIF(p->>'cumplimiento_seguridad', ''), btrim(p->>'evaluado_por'),
        v_fecha, v_estado, btrim(p->>'sustento'), NULLIF(btrim(p->>'cargo_ascenso'), ''), NULLIF(btrim(p->>'registrado_por'), ''))
    RETURNING id_evaluacion INTO v_id;

    -- Dar de baja el cargo: el tramo termina el día de la evaluación (si aún estaba abierto).
    IF v_estado = 'baja' AND v_tramo IS NOT NULL THEN
        UPDATE personal_cargo_historial
        SET fecha_fin = GREATEST(v_fecha, fecha_inicio)
        WHERE id_cargo_historial = v_tramo AND (fecha_fin IS NULL OR fecha_fin > v_fecha);
    END IF;
    RETURN v_id;
END $$;
REVOKE ALL ON FUNCTION public.fn_guardar_evaluacion_cargo(jsonb) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.fn_guardar_evaluacion_cargo(jsonb) TO authenticated;

NOTIFY pgrst, 'reload schema';
